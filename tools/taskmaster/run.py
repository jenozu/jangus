#!/usr/bin/env python3
"""Deterministic task runner for the Jangus development plan (stdlib only).

Runs the verify command of every task tagged `runner: kernel` in .taskmaster/tasks/tasks.json,
in dependency order, with zero model calls. A task is marked done only after its verify
command passed. This script never imports model or provider code (a test enforces that).

Run from the repo root:  python3 tools/taskmaster/run.py <command>

Commands:
  plan                       list pending kernel tasks in dependency order (runs nothing)
  run [--from ID|--only ID]  run the verify commands; stop at the first failure
  checklist [--out PATH]     write the generated DETERMINISTIC.md
  show TASK [--run N] [--failure K] [--context 20]
                             print raw log lines (at most 200) for a recorded run
  prune [--days 14] [--dry-run]
                             delete raw logs older than the retention period

Every step saves its full output under runs/ and prints one small JSON envelope (REDUCE.md).

Exit codes: 0 ok, 1 a check failed or a command was refused, 2 usage or config error.
"""
import argparse
import datetime
import hashlib
import json
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

import extractors  # sibling modules (tools/taskmaster/): pure extractors, output reduction
import reduction
import tasks

HERE = Path(__file__).resolve().parent
DEFAULT_ROOT = HERE.parent.parent
DEFAULT_ALLOWLIST = HERE / "allowlist.json"
GENERATED_MARK = "<!-- GENERATED by tools/taskmaster/run.py checklist. Do not edit by hand. -->"
TAIL_LINES = 20
OPERATOR_CHARS = set("();<>|&")
PYTHON_ALIASES = {"python", "python3"}  # mapped to the running interpreter (portable)
SKIPPED_STATUSES = {"done", "cancelled", "deferred"}


class Refused(Exception):
    """A command was refused before running (fail closed)."""


class ConfigError(Exception):
    """The allowlist or the task file cannot be used."""


# ---------- output helpers ----------

def say(text=""):
    enc = sys.stdout.encoding or "utf-8"
    print(str(text).encode(enc, "replace").decode(enc))


def tail(data: bytes, n: int = TAIL_LINES) -> list[str]:
    return data.decode("utf-8", "replace").splitlines()[-n:]


# ---------- allowlist and command parsing ----------

def load_allowlist(path: Path) -> dict:
    try:
        raw = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise ConfigError(f"cannot read allowlist {path}: {e}") from e
    allowed = raw.get("allowed") if isinstance(raw, dict) else None
    if not isinstance(allowed, list) or not all(
        isinstance(p, list) and p and all(isinstance(x, str) and x for x in p) for p in allowed
    ):
        raise ConfigError("allowlist 'allowed' must be a list of non-empty lists of strings")
    timeout = raw.get("default_timeout_seconds", 900)
    retries = raw.get("max_transient_retries", 0)
    if not (isinstance(timeout, int) and not isinstance(timeout, bool) and timeout > 0):
        raise ConfigError("allowlist default_timeout_seconds must be a positive int")
    if not (isinstance(retries, int) and not isinstance(retries, bool) and retries >= 0):
        raise ConfigError("allowlist max_transient_retries must be an int >= 0")
    return {"allowed": allowed, "timeout": timeout, "retries": retries}


def parse_command(text) -> list[str]:
    """Split a verify string into an argv list. Shell syntax is refused, never interpreted."""
    if not isinstance(text, str) or not text.strip():
        raise Refused("empty verify command")
    if text.strip().lower() == "manual":
        raise Refused("verify is 'manual': there is no command to run")
    if "\n" in text or "\r" in text or "`" in text:
        raise Refused("newline or backtick in command")
    lex = shlex.shlex(text, posix=True, punctuation_chars=True)
    lex.whitespace_split = True
    try:
        argv = list(lex)
    except ValueError as e:
        raise Refused(f"cannot parse command: {e}") from e
    for tok in argv:
        if tok and set(tok) <= OPERATOR_CHARS:
            raise Refused(f"shell operator '{tok}' is not allowed")
    if not argv:
        raise Refused("empty verify command")
    return argv


def check_allowed(argv: list[str], allowed: list[list[str]]) -> None:
    if not any(argv[: len(p)] == p for p in allowed):
        raise Refused(f"command not on the allowlist: {' '.join(argv)}")


def resolve_executable(argv: list[str]) -> list[str]:
    exe = argv[0]
    if exe in PYTHON_ALIASES:
        return [sys.executable, *argv[1:]]
    found = shutil.which(exe)
    if found is None:
        raise Refused(f"executable not found: {exe}")
    return [found, *argv[1:]]


def resolve_cwd(root: Path, item: dict) -> Path:
    rel = item.get("verifyCwd") or "."
    root_r = root.resolve()
    cwd = (root_r / rel).resolve()
    if cwd != root_r and root_r not in cwd.parents:
        raise Refused(f"cwd '{rel}' is outside the repo")
    if not cwd.is_dir():
        raise Refused(f"cwd '{rel}' is not a directory")
    return cwd


def check_extract(item: dict) -> str:
    name = item.get("extract", extractors.DEFAULT_EXTRACTOR)
    if not isinstance(name, str) or name not in extractors.REGISTRY:
        raise Refused(f"unknown extractor '{name}' (known: {', '.join(extractors.names())})")
    return name


def prepare(item: dict, root: Path, cfg: dict) -> dict:
    """Parse and check one task's verify step without running anything."""
    argv = parse_command(item.get("verify"))
    check_allowed(argv, cfg["allowed"])
    return {
        "argv": argv,
        "cwd": resolve_cwd(root, item),
        "timeout": item.get("verifyTimeoutSeconds", cfg["timeout"]),
        "expected_exit": item.get("verifyExpectedExit", 0),
        "retries": cfg["retries"],
        "extract": check_extract(item),
    }


# ---------- executing one step ----------

def run_step(step: dict) -> dict:
    """Run one prepared step. Retries only after a timeout (transient); a failed check is final."""
    argv = resolve_executable(step["argv"])
    started = tasks.now()
    t0 = datetime.datetime.now()
    attempts = 0
    out = err = b""
    code = None
    error = None
    while True:
        attempts += 1
        try:
            proc = subprocess.run(  # noqa: S603 - argv list, allowlisted, no shell
                argv, cwd=step["cwd"], capture_output=True, timeout=step["timeout"],
                shell=False, check=False,
            )
            out, err, code, error = proc.stdout, proc.stderr, proc.returncode, None
            break
        except subprocess.TimeoutExpired as e:
            out, err = e.stdout or b"", e.stderr or b""
            error = f"timeout after {step['timeout']}s"
            if attempts > step["retries"]:
                break
        except OSError as e:
            error = f"cannot start command: {e}"
            break
    return {
        "started": started,
        "ended": tasks.now(),
        "seconds": round((datetime.datetime.now() - t0).total_seconds(), 2),
        "exit_code": code,
        "expected_exit": step["expected_exit"],
        "passed": error is None and code == step["expected_exit"],
        "error": error,
        "attempts": attempts,
        "stdout_sha256": hashlib.sha256(out).hexdigest(),
        "stdout_tail": tail(out),
        "stderr_tail": tail(err),
        "_stdout": out,  # full output for the reducer; never written to runs.jsonl
        "_stderr": err,
    }


def record_run(path: Path, task_id, command: str, result: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    row = {"task": task_id, "command": command,
           **{k: v for k, v in result.items() if not k.startswith("_")}}
    with path.open("a", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(row, ensure_ascii=False) + "\n")


def write_handoff(directory: Path, item: dict, command: str, reason: str,
                  result: dict | None) -> Path:
    """Write handoff/TASK-<id>.md for the owner or a chat session. No model is called."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"TASK-{item['id']}.md"
    lines = [
        f"# Handoff: task {item['id']} {item.get('title', '')}",
        "",
        "A kernel step failed. No model was called. The owner or a chat session decides next.",
        "",
        "- Suggested runner: model",
        f"- Status: {item.get('status', 'pending')} (unchanged)",
        f"- Failing command: `{command}`",
        f"- Reason: {reason}",
    ]
    if result:
        lines += [f"- Exit code: {result['exit_code']} (expected {result['expected_exit']})",
                  f"- Started: {result['started']}, ended: {result['ended']}",
                  f"- stdout sha256: {result['stdout_sha256']}"]
    lines += ["", "## Task", "", f"Description: {item.get('description', '')}", "",
              f"Test strategy: {item.get('testStrategy', '')}", "",
              f"Details:\n\n{item.get('details', '')}", ""]
    if result:
        lines += [f"## Last {TAIL_LINES} lines of stdout", "", "```", *result["stdout_tail"], "```",
                  "", f"## Last {TAIL_LINES} lines of stderr", "", "```", *result["stderr_tail"],
                  "```", ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return path


# ---------- planning ----------

def kernel_order(task_list: list[dict]) -> list[dict]:
    """Kernel-tagged top-level tasks, dependencies first, ties by id."""
    kernel = {t["id"]: t for t in task_list if t.get("runner") == "kernel"}
    deps = {i: sorted(d for d in t.get("dependencies", []) if d in kernel)
            for i, t in kernel.items()}
    order: list[int] = []
    remaining = set(kernel)
    while remaining:
        ready = sorted(i for i in remaining if all(d in order for d in deps[i]))
        if not ready:
            raise ConfigError("dependency cycle among kernel tasks: "
                              + ", ".join(str(i) for i in sorted(remaining)))
        order.append(ready[0])
        remaining.discard(ready[0])
    return [kernel[i] for i in order]


def pending_kernel(task_list: list[dict]) -> list[dict]:
    return [t for t in kernel_order(task_list) if tasks.status_of(t) not in SKIPPED_STATUSES]


def load_tasks(a) -> tuple[dict, list[dict]]:
    path = Path(a.file)
    if not path.exists():
        raise ConfigError(f"{path} not found")
    data = tasks.load(str(path), a.tag)
    return data, data[a.tag]["tasks"]


# ---------- commands ----------

def cmd_plan(a) -> int:
    cfg = load_allowlist(Path(a.allowlist))
    _, task_list = load_tasks(a)
    todo = pending_kernel(task_list)
    if not todo:
        say("no pending kernel tasks")
        return 0
    done = tasks.done_ids(task_list)
    refused = 0
    for t in todo:
        note = ""
        try:
            step = prepare(t, Path(a.root), cfg)
            cmd = " ".join(step["argv"])
        except Refused as e:
            refused += 1
            cmd = str(t.get("verify"))
            note = f"  REFUSED: {e}"
        miss = tasks.unmet(t, None, done)
        if miss:
            note += f"  (blocked by {', '.join(miss)})"
        say(f"{t['id']} {tasks.ICON.get(tasks.status_of(t), '[ ]')} {t.get('title', '')}"
            f"  ->  {cmd}{note}")
    return 1 if refused else 0


def fail(a, item, command, reason, result) -> int:
    say(f"FAILED task {item['id']}: {reason}")
    say(f"command: {command}")
    if result:
        say(f"exit code: {result['exit_code']} (expected {result['expected_exit']})")
        say("details: see the envelope above; full output: run.py show " + str(item["id"]))
    path = write_handoff(Path(a.handoff_dir), item, command, reason, result)
    say(f"handoff written: {path}")
    say("stopped: later tasks were not run; status unchanged")
    return 1


def failure_reason(result: dict, envelope: dict) -> str:
    if result["error"]:
        return result["error"]
    if not result["passed"]:
        return "check failed"
    if envelope["status"] == "error":
        return f"extractor failed: {envelope.get('error', '')}"
    return "extractor reported failed checks"


def mark_done(a, item, result, was_done: bool) -> None:
    note = (f"kernel run passed: exit {result['exit_code']}, {result['seconds']}s, "
            f"stdout sha256 {result['stdout_sha256']}")
    if was_done:
        note = "re-verified. " + note
    else:
        tasks.cmd_set_status(argparse.Namespace(file=a.file, tag=a.tag, id=str(item["id"]),
                                                status="done", force=False))
    tasks.cmd_log(argparse.Namespace(file=a.file, tag=a.tag, id=str(item["id"]), text=note))


def cmd_run(a) -> int:
    cfg = load_allowlist(Path(a.allowlist))
    root = Path(a.root)
    _, task_list = load_tasks(a)
    if a.only is not None:
        item, parent = tasks.lookup(task_list, a.only)
        if item is None or parent is not None:
            raise ConfigError(f"{a.only} is not a top-level task")
        if item.get("runner") != "kernel":
            raise ConfigError(f"task {a.only} is not tagged runner: kernel; refusing to run it")
        sequence = [item["id"]]
    else:
        sequence = [t["id"] for t in pending_kernel(task_list)]
        if a.from_id is not None:
            try:
                start = int(a.from_id)
            except ValueError:
                raise ConfigError(f"bad id '{a.from_id}'") from None
            if start not in sequence:
                raise ConfigError(f"task {start} is not in the pending kernel plan")
            sequence = sequence[sequence.index(start):]
    if not sequence:
        say("no pending kernel tasks")
        return 0
    passed = skipped = 0
    for tid in sequence:
        _, task_list = load_tasks(a)  # state may have changed after the previous task
        item, _ = tasks.lookup(task_list, str(tid))
        was_done = tasks.status_of(item) == "done"
        miss = tasks.unmet(item, None, tasks.done_ids(task_list))
        if miss and not was_done:
            say(f"skip {tid}: blocked by {', '.join(miss)}")
            skipped += 1
            continue
        command = str(item.get("verify"))
        try:
            step = prepare(item, root, cfg)
            command = " ".join(step["argv"])
            result = run_step(step)
        except Refused as e:
            return fail(a, item, command, f"refused: {e}", None)
        record_run(Path(a.runs_log), tid, command, result)
        envelope, line = reduction.reduce_step(item, result, root=root,
                                               runs_dir=Path(a.runs_dir), extract=step["extract"])
        say(line)
        if envelope["status"] != "pass":
            return fail(a, item, command, failure_reason(result, envelope), result)
        try:
            mark_done(a, item, result, was_done)
        except SystemExit:
            say(f"task {tid}: verify passed but the status could not be updated")
            return 1
        say(f"ok {tid} {item.get('title', '')}  ({result['seconds']}s)")
        passed += 1
    say(f"{passed} passed, {skipped} skipped")
    return 0


def cmd_show(a) -> int:
    try:
        lines, warnings = reduction.show(Path(a.root), Path(a.runs_dir), a.task, a.run,
                                         a.failure, a.context)
    except reduction.ReductionError as e:
        raise ConfigError(str(e)) from e
    for w in warnings:
        print(w, file=sys.stderr)
    for ln in lines:
        say(ln)
    return 0


def cmd_prune(a) -> int:
    try:
        r = reduction.prune(Path(a.root), Path(a.runs_dir), a.days, a.dry_run)
    except reduction.ReductionError as e:
        raise ConfigError(str(e)) from e
    verb = "would delete" if r["dry_run"] else "deleted"
    say(f"{verb} {r['files']} raw log(s); {r['entries']} index entr(ies) "
        f"older than {a.days} days; {r['kept']} kept")
    return 0


def render_checklist(task_list: list[dict], cfg: dict) -> str:
    lines = [
        GENERATED_MARK, "",
        "# DETERMINISTIC.md: kernel-run tasks", "",
        "Generated from `.taskmaster/tasks/tasks.json`. Each task below is tagged "
        "`runner: kernel`: same input, same result, a command checks it, no model call. "
        "Run them with `python3 tools/taskmaster/run.py run`; list them with `plan`.", "",
        "| Status | ID | Title | Command |", "|---|---|---|---|",
    ]
    for t in kernel_order(task_list):
        box = "[x]" if tasks.status_of(t) == "done" else "[ ]"
        try:
            cmd = " ".join(parse_command(t.get("verify")))
        except Refused:
            cmd = f"{t.get('verify')} (refused)"
        lines.append(f"| {box} | {t['id']} | {t.get('title', '')} | `{cmd}` |")
    lines += ["", f"Allowed command prefixes: {len(cfg['allowed'])} "
              "(see `tools/taskmaster/allowlist.json`). Anything else is refused.", ""]
    return "\n".join(lines)


def cmd_checklist(a) -> int:
    cfg = load_allowlist(Path(a.allowlist))
    _, task_list = load_tasks(a)
    out = Path(a.out) if a.out else Path(a.root) / "DETERMINISTIC.md"
    if out.exists() and not a.force:
        first = out.read_text(encoding="utf-8").splitlines()[:1]
        if first != [GENERATED_MARK]:
            raise ConfigError(f"{out} exists and is not generated; use --force to overwrite")
    out.write_text(render_checklist(task_list, cfg), encoding="utf-8", newline="\n")
    say(f"wrote {out}")
    return 0


# ---------- entry point ----------

def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, allow_abbrev=False,  # show has --run
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--root", default=str(DEFAULT_ROOT), help="repo root (default: this repo)")
    p.add_argument("--file", help="tasks.json (default: <root>/.taskmaster/tasks/tasks.json)")
    p.add_argument("--tag", default="master")
    p.add_argument("--allowlist", default=str(DEFAULT_ALLOWLIST))
    p.add_argument("--handoff-dir", help="default: <root>/handoff")
    p.add_argument("--runs-log", help="default: <root>/.taskmaster/runs/runs.jsonl")
    p.add_argument("--runs-dir", help="raw logs, index and envelopes (default: <root>/runs)")
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("plan").set_defaults(fn=cmd_plan)
    sp = sub.add_parser("run")
    group = sp.add_mutually_exclusive_group()
    group.add_argument("--from", dest="from_id", help="start at this task id")
    group.add_argument("--only", help="run just this task (re-verifies it if already done)")
    sp.set_defaults(fn=cmd_run)
    sp = sub.add_parser("checklist")
    sp.add_argument("--out", help="default: <root>/DETERMINISTIC.md")
    sp.add_argument("--force", action="store_true", help="overwrite a file that is not generated")
    sp.set_defaults(fn=cmd_checklist)
    sp = sub.add_parser("show", help="print raw lines of a recorded run, at most 200")
    sp.add_argument("task", help="task id")
    sp.add_argument("--run", type=int, help="run number (default: the latest)")
    sp.add_argument("--failure", type=int, help="show lines around the Kth failure (from 1)")
    sp.add_argument("--context", type=int, default=reduction.SHOW_DEFAULT_CONTEXT,
                    help="lines on each side of the failure (default 20)")
    sp.set_defaults(fn=cmd_show)
    sp = sub.add_parser("prune", help="delete raw logs older than the retention period")
    sp.add_argument("--days", type=int, default=reduction.RETENTION_DAYS)
    sp.add_argument("--dry-run", action="store_true", help="count only, delete nothing")
    sp.set_defaults(fn=cmd_prune)
    return p


def main(argv=None) -> int:
    a = build_parser().parse_args(argv)
    root = Path(a.root)
    a.file = a.file or str(root / ".taskmaster" / "tasks" / "tasks.json")
    a.handoff_dir = a.handoff_dir or str(root / "handoff")
    a.runs_log = a.runs_log or str(root / ".taskmaster" / "runs" / "runs.jsonl")
    a.runs_dir = a.runs_dir or str(root / "runs")
    try:
        return a.fn(a)
    except ConfigError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
